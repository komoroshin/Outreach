def lic(name, units, roy, active_share, inf_margin_mo, cert):
    active = units*active_share
    r_roy = units*roy; r_inf = active*inf_margin_mo*12
    tot = r_roy+r_inf+cert
    print(f"{name:<26} устройств {units:>7,} | роялти ${r_roy:>9,.0f} | маржа на инференсе ${r_inf:>9,.0f} "
          f"| сертификация ${cert:>6,.0f} | ИТОГО ${tot:>10,.0f}")
    return tot
